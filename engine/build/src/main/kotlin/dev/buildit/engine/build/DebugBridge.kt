package dev.buildit.engine.build

/**
 * The console connection injected into debug builds only. A small ContentProvider in the built app
 * starts with its process and forwards the app's own logcat lines, activity lifecycle events and
 * uncaught exceptions (with their stack traces) to Build It's console provider on the same device.
 *
 * The user's sources are never changed: the class is compiled from generated source next to R and
 * BuildConfig, and the manifest entries are added to the compiled manifest only. If Build It is not
 * installed the bridge does nothing.
 */
object DebugBridge {
    const val PACKAGE = "dev.buildit.debugbridge"
    const val CLASS = "$PACKAGE.BuildItDebugBridge"

    /** Where the bridge sends entries: Build It's application id and its console provider authority. */
    data class Host(val packageName: String, val authority: String)

    /** Authority of the bridge's own provider inside the built app (must be unique per app). */
    fun ownAuthority(applicationId: String) = "$applicationId.buildit-debug-bridge"

    fun source(host: Host): String = """
        |/* Generated by Build It for debug builds. Not part of your project's sources. */
        |package $PACKAGE;
        |
        |import android.app.Activity;
        |import android.app.Application;
        |import android.content.ContentProvider;
        |import android.content.ContentValues;
        |import android.content.Context;
        |import android.database.Cursor;
        |import android.net.Uri;
        |import android.os.Bundle;
        |import android.os.Process;
        |import android.util.Log;
        |import java.io.BufferedReader;
        |import java.io.InputStreamReader;
        |import java.util.ArrayList;
        |
        |public final class BuildItDebugBridge extends ContentProvider {
        |    private static final String HOST = "${host.packageName}";
        |    private static final Uri ENTRIES = Uri.parse("content://${host.authority}/entries");
        |    private static final ArrayList<ContentValues> queue = new ArrayList<ContentValues>();
        |    private static Context app;
        |    private static long session;
        |
        |    @Override public boolean onCreate() {
        |        Context c = getContext();
        |        if (c == null) return true;
        |        app = c.getApplicationContext();
        |        try { app.getPackageManager().getPackageInfo(HOST, 0); } catch (Exception e) { return true; }
        |        session = System.currentTimeMillis();
        |        enqueue("start", "Process " + Process.myPid() + " started", null);
        |        installCrashHandler();
        |        if (app instanceof Application) watchActivities((Application) app);
        |        startThread("BuildItLogcat", new Runnable() { public void run() { readLogcat(); } });
        |        startThread("BuildItConsole", new Runnable() { public void run() { flushLoop(); } });
        |        return true;
        |    }
        |
        |    private static void startThread(String name, Runnable r) {
        |        Thread t = new Thread(r, name);
        |        t.setDaemon(true);
        |        t.start();
        |    }
        |
        |    private static ContentValues entry(String kind, String text, String thread) {
        |        ContentValues v = new ContentValues();
        |        v.put("session", session);
        |        v.put("pid", Process.myPid());
        |        v.put("time", System.currentTimeMillis());
        |        v.put("kind", kind);
        |        v.put("text", text);
        |        if (thread != null) v.put("thread", thread);
        |        return v;
        |    }
        |
        |    private static void enqueue(String kind, String text, String thread) {
        |        synchronized (queue) {
        |            if (queue.size() < 5000) queue.add(entry(kind, text, thread));
        |        }
        |    }
        |
        |    private static boolean send(ContentValues[] batch) {
        |        try {
        |            app.getContentResolver().bulkInsert(ENTRIES, batch);
        |            return true;
        |        } catch (Throwable t) {
        |            return false;
        |        }
        |    }
        |
        |    private static void flushLoop() {
        |        while (true) {
        |            ContentValues[] batch;
        |            synchronized (queue) {
        |                int n = Math.min(queue.size(), 200);
        |                batch = new ContentValues[n];
        |                for (int i = 0; i < n; i++) batch[i] = queue.get(i);
        |            }
        |            if (batch.length > 0 && send(batch)) {
        |                synchronized (queue) { queue.subList(0, batch.length).clear(); }
        |            }
        |            try { Thread.sleep(batch.length == 200 ? 20 : 300); } catch (InterruptedException e) { return; }
        |        }
        |    }
        |
        |    private static void readLogcat() {
        |        try {
        |            java.lang.Process p = Runtime.getRuntime().exec(new String[] { "logcat", "-v", "threadtime", "--pid=" + Process.myPid() });
        |            BufferedReader r = new BufferedReader(new InputStreamReader(p.getInputStream(), "UTF-8"));
        |            String line;
        |            while ((line = r.readLine()) != null) {
        |                if (line.startsWith("--------- beginning of")) continue;
        |                enqueue("log", line, null);
        |            }
        |        } catch (Throwable t) {
        |            enqueue("bridge", "Logcat is not available: " + t, null);
        |        }
        |    }
        |
        |    private static void installCrashHandler() {
        |        final Thread.UncaughtExceptionHandler previous = Thread.getDefaultUncaughtExceptionHandler();
        |        Thread.setDefaultUncaughtExceptionHandler(new Thread.UncaughtExceptionHandler() {
        |            public void uncaughtException(Thread t, Throwable e) {
        |                ArrayList<ContentValues> pending;
        |                synchronized (queue) { pending = new ArrayList<ContentValues>(queue); queue.clear(); }
        |                pending.add(entry("crash", Log.getStackTraceString(e), t.getName()));
        |                send(pending.toArray(new ContentValues[0]));
        |                if (previous != null) previous.uncaughtException(t, e);
        |                else { Process.killProcess(Process.myPid()); System.exit(10); }
        |            }
        |        });
        |    }
        |
        |    private static void watchActivities(Application application) {
        |        application.registerActivityLifecycleCallbacks(new Application.ActivityLifecycleCallbacks() {
        |            private void log(Activity a, String what) { enqueue("lifecycle", a.getClass().getName() + " " + what, null); }
        |            public void onActivityCreated(Activity a, Bundle b) { log(a, "created"); }
        |            public void onActivityStarted(Activity a) { log(a, "started"); }
        |            public void onActivityResumed(Activity a) { log(a, "resumed"); }
        |            public void onActivityPaused(Activity a) { log(a, "paused"); }
        |            public void onActivityStopped(Activity a) { log(a, "stopped"); }
        |            public void onActivitySaveInstanceState(Activity a, Bundle b) { }
        |            public void onActivityDestroyed(Activity a) { log(a, "destroyed"); }
        |        });
        |    }
        |
        |    @Override public Cursor query(Uri u, String[] p, String s, String[] a, String o) { return null; }
        |    @Override public String getType(Uri u) { return null; }
        |    @Override public Uri insert(Uri u, ContentValues v) { return null; }
        |    @Override public int delete(Uri u, String s, String[] a) { return 0; }
        |    @Override public int update(Uri u, ContentValues v, String s, String[] a) { return 0; }
        |}
        |""".trimMargin()
}
