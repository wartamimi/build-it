package dev.buildit.engine.blocks

import dev.buildit.engine.project.SourceLanguage

/** Prints a [Program] as source code. Output is deterministic for a given program. */
interface Backend {
    fun generate(p: Program): String

    companion object {
        fun of(language: SourceLanguage): Backend = when (language) {
            SourceLanguage.Java -> JavaBackend
            SourceLanguage.Kotlin -> KotlinBackend
        }
    }
}

private class Out {
    private val sb = StringBuilder()
    private var indent = 0
    fun line(s: String = "") { if (s.isEmpty()) sb.append('\n') else sb.append("    ".repeat(indent)).append(s).append('\n') }
    fun block(open: String, close: String = "}", body: () -> Unit) { line(open); indent++; body(); indent--; line(close) }
    fun open(s: String) { line(s); indent++ }
    fun mid(s: String) { indent--; line(s); indent++ }
    fun close(s: String = "}") { indent--; line(s) }
    fun raw(code: String) = code.trimEnd().lines().forEach { line(it.trimEnd()) }
    override fun toString() = sb.toString()
}

private fun header(source: String) = listOf(
    "/*",
    " * Generated by Build It from blocks ($source).",
    " * Edit the blocks instead of this file: if this file is changed by hand, Build It detects it",
    " * and asks before generating it again.",
    " */",
)

private fun handlerName(prefix: String, view: String, suffix: String) = prefix + view.replaceFirstChar { it.uppercase() } + suffix
private fun procName(name: String) = "run" + name.replaceFirstChar { it.uppercase() }

private val placeholder = Regex("\\{(\\w+)\\}")

/** Fills a template: inputs are printed with [expr], text fields with [str], other fields as is. */
private fun fill(template: String, inputs: Map<String, Expr>, fields: Map<String, TField>, expr: (Expr) -> String, str: (String) -> String): String =
    placeholder.replace(template) { m ->
        val n = m.groupValues[1]
        inputs[n]?.let(expr) ?: when (val f = fields[n]) {
            is TField.Raw -> f.code
            is TField.Str -> str(f.text)
            null -> m.value
        }
    }

private fun usesClass(p: Program, predicate: (Stmt) -> Boolean): Boolean {
    fun any(list: List<Stmt>): Boolean = list.any { s ->
        predicate(s) || when (s) {
            is If -> any(s.then) || any(s.otherwise.orEmpty())
            is Repeat -> any(s.body)
            is While -> any(s.body)
            is ForRange -> any(s.body)
            is ForEach -> any(s.body)
            else -> false
        }
    }
    return any(p.onCreate) || p.lifecycle.values.any(::any) || p.clicks.any { any(it.body) } ||
        p.checkedChanges.any { any(it.body) } || p.procedures.any { any(it.body) } || p.componentEvents.values.any(::any)
}

private fun Program.has(t: ComponentType) = components.any { it.type == t }
private fun Program.ofType(t: ComponentType) = components.filter { it.type == t }

/** Lines that stop timers and release players when the screen is destroyed. */
private fun Program.cleanup(kotlin: Boolean): List<String> =
    ofType(ComponentType.Timer).map { "${it.name}.removeCallbacksAndMessages(null)" + if (kotlin) "" else ";" } +
        ofType(ComponentType.Sound).map { handlerName("stop", it.name, "") + "()" + if (kotlin) "" else ";" }

private fun imports(p: Program): List<String> {
    val set = sortedSetOf("android.app.Activity", "android.os.Bundle")
    p.views.forEach { set += it.className }
    if (p.variables.any { it.type == ValueType.TextList || it.type == ValueType.NumberList }) set += "java.util.ArrayList"
    if (p.variables.any { it.type == ValueType.TextMap }) set += "java.util.HashMap"
    set += p.imports
    if (usesClass(p) { it is Toast }) set += "android.widget.Toast"
    if (usesClass(p) { it is Log }) set += "android.util.Log"
    if (usesClass(p) { it is StartActivity }) set += "android.content.Intent"
    if (usesClass(p) { it is SetVisibility }) set += "android.view.View"
    if (usesClass(p) { it is SetTextColor }) set += "android.graphics.Color"
    if (usesClass(p) { it is OpenLink }) { set += "android.content.Intent"; set += "android.net.Uri" }
    if (p.has(ComponentType.Timer)) { set += "android.os.Handler"; set += "android.os.Looper" }
    if (p.has(ComponentType.Storage)) set += "android.content.SharedPreferences"
    if (p.has(ComponentType.Dialog)) set += "android.app.AlertDialog"
    if (p.has(ComponentType.Sound)) set += "android.media.MediaPlayer"
    return set.toList()
}

object JavaBackend : Backend {
    override fun generate(p: Program): String = Out().apply {
        line("package ${p.packageName};")
        line()
        imports(p).forEach { line("import $it;") }
        line()
        header(".buildit/blocks/${p.className}.json").forEach(::line)
        block("public class ${p.className} extends Activity {") {
            if (Helper.RandomInt in p.helpers) line("private static final java.util.Random RANDOM = new java.util.Random();")
            p.variables.forEach { v -> line("private ${type(v.type)} ${v.name} = ${initial(v.type)};") }
            p.views.forEach { v -> line("private ${v.className.substringAfterLast('.')} ${v.id};") }
            p.components.forEach { c ->
                when (c.type) {
                    ComponentType.Timer -> line("private final Handler ${c.name} = new Handler(Looper.getMainLooper());")
                    ComponentType.Storage -> line("private SharedPreferences ${c.name};")
                    ComponentType.Sound -> line("private MediaPlayer ${c.name};")
                    ComponentType.Dialog -> Unit
                }
            }
            if (p.variables.isNotEmpty() || p.views.isNotEmpty() || p.components.any { it.type != ComponentType.Dialog } || Helper.RandomInt in p.helpers) line()

            line("@Override")
            block("protected void onCreate(Bundle savedInstanceState) {") {
                line("super.onCreate(savedInstanceState);")
                line("setContentView(R.layout.${p.layout});")
                p.views.forEach { line("${it.id} = findViewById(R.id.${it.id});") }
                p.ofType(ComponentType.Storage).forEach { line("${it.name} = getSharedPreferences(${str(it.name)}, MODE_PRIVATE);") }
                p.clicks.forEach { line("${it.view}.setOnClickListener(v -> ${handlerName("on", it.view, "Click")}());") }
                p.checkedChanges.forEach { line("${it.view}.setOnCheckedChangeListener((button, isChecked) -> ${handlerName("on", it.view, "CheckedChange")}());") }
                stmts(p.onCreate)
            }
            val cleanup = p.cleanup(kotlin = false)
            val lifecycle = if (cleanup.isNotEmpty() && Lifecycle.Destroy !in p.lifecycle) p.lifecycle + (Lifecycle.Destroy to emptyList()) else p.lifecycle
            lifecycle.toSortedMap().forEach { (lc, body) ->
                line()
                line("@Override")
                block("protected void ${lc.method}() {") {
                    if (lc == Lifecycle.Destroy) cleanup.forEach { line(it) }
                    line("super.${lc.method}();")
                    stmts(body)
                }
            }
            p.clicks.forEach { h -> line(); block("private void ${handlerName("on", h.view, "Click")}() {") { stmts(h.body) } }
            p.checkedChanges.forEach { h -> line(); block("private void ${handlerName("on", h.view, "CheckedChange")}() {") { stmts(h.body) } }
            p.procedures.forEach { pr ->
                line()
                block("private void ${procName(pr.name)}(${pr.params.joinToString(", ") { "${if (it.type.isCollection) "" else "final "}${type(it.type)} ${it.name}" }}) {") { stmts(pr.body) }
            }
            p.components.forEach { c -> component(c, p.componentEvents[c.name].orEmpty()) }
            helpers(p.helpers)
            p.templateHelpers.forEach { h -> h.java?.let { line(); raw(it) } }
        }
    }.toString()

    private fun Out.component(c: Component, event: List<Stmt>) {
        val n = c.name
        when (c.type) {
            ComponentType.Timer -> {
                line()
                block("private void ${handlerName("start", n, "")}(final long delay, final boolean repeat) {") {
                    line("$n.removeCallbacksAndMessages(null);")
                    block("$n.postDelayed(new Runnable() {", "}, Math.max(delay, 0));") {
                        line("@Override")
                        block("public void run() {") {
                            line("if (repeat) $n.postDelayed(this, Math.max(delay, 1));")
                            line("${handlerName("on", n, "Tick")}();")
                        }
                    }
                }
                line(); block("private void ${handlerName("on", n, "Tick")}() {") { stmts(event) }
            }
            ComponentType.Dialog -> { line(); block("private void ${handlerName("on", n, "Ok")}() {") { stmts(event) } }
            ComponentType.Sound -> {
                line()
                block("private void ${handlerName("play", n, "")}(int sound) {") {
                    line("${handlerName("stop", n, "")}();")
                    line("$n = MediaPlayer.create(this, sound);")
                    line("if ($n == null) return;")
                    line("$n.setOnCompletionListener(player -> { ${handlerName("stop", n, "")}(); ${handlerName("on", n, "Done")}(); });")
                    line("$n.start();")
                }
                line()
                block("private void ${handlerName("stop", n, "")}() {") {
                    block("if ($n != null) {") { line("$n.release();"); line("$n = null;") }
                }
                line(); block("private void ${handlerName("on", n, "Done")}() {") { stmts(event) }
            }
            ComponentType.Storage -> Unit
        }
    }

    private fun type(t: ValueType) = when (t) {
        ValueType.Boolean -> "boolean"; ValueType.Number -> "double"; ValueType.Text -> "String"; ValueType.TextList -> "ArrayList<String>"
        ValueType.NumberList -> "ArrayList<Double>"; ValueType.TextMap -> "HashMap<String, String>"
    }

    private fun initial(t: ValueType) = when (t) {
        ValueType.Boolean -> "false"; ValueType.Number -> "0"; ValueType.Text -> "\"\""; ValueType.TextList, ValueType.NumberList -> "new ArrayList<>()"
        ValueType.TextMap -> "new HashMap<>()"
    }

    private fun Out.stmts(list: List<Stmt>) = list.forEach { stmt(it) }

    private fun Out.stmt(s: Stmt) {
        when (s) {
            is If -> {
                open("if (${c(s.cond)}) {"); stmts(s.then)
                if (s.otherwise != null) { mid("} else {"); stmts(s.otherwise) }
                close()
            }
            is Repeat -> block("for (int ${s.counter} = 0; ${s.counter} < (int) ${e(s.times)}; ${s.counter}++) {") { stmts(s.body) }
            // A constant condition would make javac reject the code after (or inside) the loop as unreachable
            is While -> block("while (${if (s.cond is BoolLit) "Boolean.${s.cond.value.toString().uppercase()}" else c(s.cond)}) {") { stmts(s.body) }
            is ForRange -> block("for (${s.variable} = ${e(s.from)}; ${s.variable} <= ${e(s.to)}; ${s.variable}++) {") { stmts(s.body) }
            is SetVar -> line("${s.name} = ${c(s.value)};")
            is ChangeVar -> line("${s.name} += ${e(s.by)};")
            is ListAdd -> line("${s.list}.add(${e(s.item)});")
            is ListClear -> line("${s.list}.clear();")
            is SetViewText -> line("${s.view}.setText(${c(s.text)});")
            is SetVisibility -> line("${s.view}.setVisibility(View.${s.visibility.uppercase()});")
            is SetEnabled -> line("${s.view}.setEnabled(${e(s.value)});")
            is SetChecked -> line("${s.view}.setChecked(${e(s.value)});")
            is SetTextColor -> line("${s.view}.setTextColor(Color.parseColor(${str(s.color)}));")
            is Toast -> line("Toast.makeText(this, ${e(s.text)}, Toast.LENGTH_SHORT).show();")
            is Log -> line("Log.d(\"BuildIt\", ${e(s.text)});")
            is StartActivity -> line("startActivity(new Intent(this, ${s.activity}.class));")
            Finish -> line("finish();")
            is CallProcedure -> line("${procName(s.name)}(${s.args.joinToString(", ") { c(it) }});")
            is RawStmt -> raw(s.code)
            is TimerStart -> line("${handlerName("start", s.timer, "")}((long) ${e(s.delayMs)}, ${s.repeating});")
            is TimerStop -> line("${s.timer}.removeCallbacksAndMessages(null);")
            is StorageSet -> line("${s.store}.edit().putString(${c(s.key)}, ${c(s.value)}).apply();")
            is StorageRemove -> line("${s.store}.edit().remove(${c(s.key)}).apply();")
            is DialogShow -> line("new AlertDialog.Builder(this).setTitle(${c(s.title)}).setMessage(${c(s.message)}).setPositiveButton(android.R.string.ok, (dialog, which) -> ${handlerName("on", s.dialog, "Ok")}()).show();")
            is SoundPlay -> line("${handlerName("play", s.sound, "")}(R.raw.${s.file});")
            is SoundStop -> line("${handlerName("stop", s.sound, "")}();")
            is OpenLink -> line("startActivity(new Intent(Intent.ACTION_VIEW, Uri.parse(${c(s.url)})));")
            is ForEach -> block("for (${if (s.elementType == ValueType.Number) "double" else "String"} ${s.item} : new ArrayList<>(${s.list})) {") {
                line("${s.variable} = ${s.item};")
                stmts(s.body)
            }
            is TemplateStmt -> raw(fill(s.code.java, s.inputs, s.fields, ::e, ::str))
        }
    }

    /** Expression without redundant outer parentheses, for positions that are already delimited. */
    private fun c(x: Expr): String = when (x) {
        is Binary -> "${e(x.a)} ${x.op.symbol} ${e(x.b)}"
        is Concat -> "${e(x.a)} + ${e(x.b)}"
        else -> e(x)
    }

    private fun e(x: Expr): String = when (x) {
        is BoolLit -> x.value.toString()
        is NumLit -> num(x.value)
        is StorageGet -> "${x.store}.getString(${c(x.key)}, \"\")"
        is TextLit -> str(x.value)
        is VarRef -> x.name
        is Binary -> "(${e(x.a)} ${x.op.symbol} ${e(x.b)})"
        is Not -> "!${e(x.a)}"
        is TextEquals -> "${e(x.a)}.equals(${e(x.b)})"
        is ToText -> when (x.a.type) {
            ValueType.Number -> "formatNumber(${e(x.a)})"
            else -> "String.valueOf(${e(x.a)})"
        }
        is Concat -> "(${e(x.a)} + ${e(x.b)})"
        is TextLength -> "(double) ${e(x.a)}.length()"
        is RandomInt -> "randomInt(${e(x.from)}, ${e(x.to)})"
        is Round -> "(double) Math.round(${e(x.a)})"
        is ParseNumber -> "parseNumber(${e(x.a)})"
        is ListGet -> "${x.list}.get((int) ${e(x.index)} - 1)"
        is ListSize -> "(double) ${x.list}.size()"
        is ViewText -> "${x.view}.getText().toString()"
        is ViewChecked -> "${x.view}.isChecked()"
        is RawExpr -> "String.valueOf(${x.code})"
        is TemplateExpr -> fill(x.code.java, x.inputs, x.fields, ::e, ::str)
    }

    private fun Out.helpers(h: Set<Helper>) {
        if (Helper.FormatNumber in h) {
            line()
            block("private static String formatNumber(double value) {") {
                line("if (value == Math.rint(value) && !Double.isInfinite(value) && Math.abs(value) < 1e15) return String.valueOf((long) value);")
                line("return String.valueOf(value);")
            }
        }
        if (Helper.RandomInt in h) {
            line()
            block("private static double randomInt(double from, double to) {") {
                line("int low = (int) Math.ceil(Math.min(from, to));")
                line("int high = (int) Math.floor(Math.max(from, to));")
                line("if (high < low) return low;")
                line("return low + RANDOM.nextInt(high - low + 1);")
            }
        }
        if (Helper.ParseNumber in h) {
            line()
            block("private static double parseNumber(String text) {") {
                open("try {"); line("return Double.parseDouble(text.trim());")
                mid("} catch (NumberFormatException e) {"); line("return 0;")
                close()
            }
        }
    }

    internal fun num(v: Double): String = if (v == Math.rint(v) && kotlin.math.abs(v) < 1e15) "${v.toLong()}.0" else v.toString()

    internal fun str(s: String): String = buildString {
        append('"')
        s.forEach { c ->
            when (c) {
                '\\' -> append("\\\\"); '"' -> append("\\\""); '\n' -> append("\\n"); '\r' -> append("\\r"); '\t' -> append("\\t")
                else -> if (c.code < 0x20) append("\\u%04x".format(c.code)) else append(c)
            }
        }
        append('"')
    }
}

object KotlinBackend : Backend {
    override fun generate(p: Program): String = Out().apply {
        line("package ${p.packageName}")
        line()
        imports(p).filterNot { it == "java.util.ArrayList" || it == "java.util.HashMap" }.forEach { line("import $it") }
        line()
        header(".buildit/blocks/${p.className}.json").forEach(::line)
        block("class ${p.className} : Activity() {") {
            p.variables.forEach { v -> line("private ${if (v.type.isCollection) "val" else "var"} ${v.name}: ${type(v.type)} = ${initial(v.type)}") }
            p.views.forEach { v -> line("private lateinit var ${v.id}: ${v.className.substringAfterLast('.')}") }
            p.components.forEach { c ->
                when (c.type) {
                    ComponentType.Timer -> line("private val ${c.name} = Handler(Looper.getMainLooper())")
                    ComponentType.Storage -> line("private lateinit var ${c.name}: SharedPreferences")
                    ComponentType.Sound -> line("private var ${c.name}: MediaPlayer? = null")
                    ComponentType.Dialog -> Unit
                }
            }
            if (p.variables.isNotEmpty() || p.views.isNotEmpty() || p.components.any { it.type != ComponentType.Dialog }) line()

            block("override fun onCreate(savedInstanceState: Bundle?) {") {
                line("super.onCreate(savedInstanceState)")
                line("setContentView(R.layout.${p.layout})")
                p.views.forEach { line("${it.id} = findViewById(R.id.${it.id})") }
                p.ofType(ComponentType.Storage).forEach { line("${it.name} = getSharedPreferences(${str(it.name)}, MODE_PRIVATE)") }
                p.clicks.forEach { line("${it.view}.setOnClickListener { ${handlerName("on", it.view, "Click")}() }") }
                p.checkedChanges.forEach { line("${it.view}.setOnCheckedChangeListener { _, _ -> ${handlerName("on", it.view, "CheckedChange")}() }") }
                stmts(p.onCreate)
            }
            val cleanup = p.cleanup(kotlin = true)
            val lifecycle = if (cleanup.isNotEmpty() && Lifecycle.Destroy !in p.lifecycle) p.lifecycle + (Lifecycle.Destroy to emptyList()) else p.lifecycle
            lifecycle.toSortedMap().forEach { (lc, body) ->
                line()
                block("override fun ${lc.method}() {") {
                    if (lc == Lifecycle.Destroy) cleanup.forEach { line(it) }
                    line("super.${lc.method}()")
                    stmts(body)
                }
            }
            p.clicks.forEach { h -> line(); block("private fun ${handlerName("on", h.view, "Click")}() {") { stmts(h.body) } }
            p.checkedChanges.forEach { h -> line(); block("private fun ${handlerName("on", h.view, "CheckedChange")}() {") { stmts(h.body) } }
            p.procedures.forEach { pr ->
                line()
                block("private fun ${procName(pr.name)}(${pr.params.joinToString(", ") { "${it.name}: ${type(it.type)}" }}) {") { stmts(pr.body) }
            }
            p.components.forEach { c -> component(c, p.componentEvents[c.name].orEmpty()) }
            helpers(p.helpers)
            p.templateHelpers.forEach { h -> h.kotlin?.let { line(); raw(it) } }
        }
    }.toString()

    private fun Out.component(c: Component, event: List<Stmt>) {
        val n = c.name
        when (c.type) {
            ComponentType.Timer -> {
                line()
                block("private fun ${handlerName("start", n, "")}(delay: Long, repeat: Boolean) {") {
                    line("$n.removeCallbacksAndMessages(null)")
                    block("$n.postDelayed(object : Runnable {", "}, maxOf(delay, 0L))") {
                        block("override fun run() {") {
                            line("if (repeat) $n.postDelayed(this, maxOf(delay, 1L))")
                            line("${handlerName("on", n, "Tick")}()")
                        }
                    }
                }
                line(); block("private fun ${handlerName("on", n, "Tick")}() {") { stmts(event) }
            }
            ComponentType.Dialog -> { line(); block("private fun ${handlerName("on", n, "Ok")}() {") { stmts(event) } }
            ComponentType.Sound -> {
                line()
                block("private fun ${handlerName("play", n, "")}(sound: Int) {") {
                    line("${handlerName("stop", n, "")}()")
                    line("val player = MediaPlayer.create(this, sound) ?: return")
                    line("$n = player")
                    line("player.setOnCompletionListener { ${handlerName("stop", n, "")}(); ${handlerName("on", n, "Done")}() }")
                    line("player.start()")
                }
                line()
                block("private fun ${handlerName("stop", n, "")}() {") {
                    line("$n?.release()")
                    line("$n = null")
                }
                line(); block("private fun ${handlerName("on", n, "Done")}() {") { stmts(event) }
            }
            ComponentType.Storage -> Unit
        }
    }

    private fun type(t: ValueType) = when (t) {
        ValueType.Boolean -> "Boolean"; ValueType.Number -> "Double"; ValueType.Text -> "String"; ValueType.TextList -> "ArrayList<String>"
        ValueType.NumberList -> "ArrayList<Double>"; ValueType.TextMap -> "HashMap<String, String>"
    }

    private fun initial(t: ValueType) = when (t) {
        ValueType.Boolean -> "false"; ValueType.Number -> "0.0"; ValueType.Text -> "\"\""; ValueType.TextList, ValueType.NumberList -> "ArrayList()"
        ValueType.TextMap -> "HashMap()"
    }

    private fun Out.stmts(list: List<Stmt>) = list.forEach { stmt(it) }

    private fun Out.stmt(s: Stmt) {
        when (s) {
            is If -> {
                open("if (${c(s.cond)}) {"); stmts(s.then)
                if (s.otherwise != null) { mid("} else {"); stmts(s.otherwise) }
                close()
            }
            is Repeat -> block("for (${s.counter} in 0 until ${e(s.times)}.toInt()) {") { stmts(s.body) }
            is While -> block("while (${c(s.cond)}) {") { stmts(s.body) }
            is ForRange -> {
                line("${s.variable} = ${e(s.from)}")
                block("while (${s.variable} <= ${e(s.to)}) {") { stmts(s.body); line("${s.variable} += 1.0") }
            }
            is SetVar -> line("${s.name} = ${c(s.value)}")
            is ChangeVar -> line("${s.name} += ${e(s.by)}")
            is ListAdd -> line("${s.list}.add(${e(s.item)})")
            is ListClear -> line("${s.list}.clear()")
            is SetViewText -> line("${s.view}.text = ${c(s.text)}")
            is SetVisibility -> line("${s.view}.visibility = View.${s.visibility.uppercase()}")
            is SetEnabled -> line("${s.view}.isEnabled = ${e(s.value)}")
            is SetChecked -> line("${s.view}.isChecked = ${e(s.value)}")
            is SetTextColor -> line("${s.view}.setTextColor(Color.parseColor(${str(s.color)}))")
            is Toast -> line("Toast.makeText(this, ${e(s.text)}, Toast.LENGTH_SHORT).show()")
            is Log -> line("Log.d(\"BuildIt\", ${e(s.text)})")
            is StartActivity -> line("startActivity(Intent(this, ${s.activity}::class.java))")
            Finish -> line("finish()")
            is CallProcedure -> line("${procName(s.name)}(${s.args.joinToString(", ") { c(it) }})")
            is RawStmt -> raw(s.code)
            is TimerStart -> line("${handlerName("start", s.timer, "")}(${e(s.delayMs)}.toLong(), ${s.repeating})")
            is TimerStop -> line("${s.timer}.removeCallbacksAndMessages(null)")
            is StorageSet -> line("${s.store}.edit().putString(${c(s.key)}, ${c(s.value)}).apply()")
            is StorageRemove -> line("${s.store}.edit().remove(${c(s.key)}).apply()")
            is DialogShow -> line("AlertDialog.Builder(this).setTitle(${c(s.title)}).setMessage(${c(s.message)}).setPositiveButton(android.R.string.ok) { _, _ -> ${handlerName("on", s.dialog, "Ok")}() }.show()")
            is SoundPlay -> line("${handlerName("play", s.sound, "")}(R.raw.${s.file})")
            is SoundStop -> line("${handlerName("stop", s.sound, "")}()")
            is OpenLink -> line("startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(${c(s.url)})))")
            is ForEach -> block("for (${s.item} in ArrayList(${s.list})) {") {
                line("${s.variable} = ${s.item}")
                stmts(s.body)
            }
            is TemplateStmt -> raw(fill(s.code.kotlin, s.inputs, s.fields, ::e, ::str))
        }
    }

    /** Expression without redundant outer parentheses, for positions that are already delimited. */
    private fun c(x: Expr): String = when (x) {
        is Binary -> "${e(x.a)} ${x.op.symbol} ${e(x.b)}"
        is Concat -> "${e(x.a)} + ${e(x.b)}"
        else -> e(x)
    }

    private fun e(x: Expr): String = when (x) {
        is BoolLit -> x.value.toString()
        is NumLit -> JavaBackend.num(x.value)
        is TextLit -> str(x.value)
        is VarRef -> x.name
        is Binary -> "(${e(x.a)} ${x.op.symbol} ${e(x.b)})"
        is Not -> "!${e(x.a)}"
        is TextEquals -> "(${e(x.a)} == ${e(x.b)})"
        is ToText -> when (x.a.type) {
            ValueType.Number -> "formatNumber(${e(x.a)})"
            else -> if (x.a is Not || x.a is Binary) "(${e(x.a)}).toString()" else "${e(x.a)}.toString()"
        }
        is Concat -> "(${e(x.a)} + ${e(x.b)})"
        is TextLength -> "${e(x.a)}.length.toDouble()"
        is RandomInt -> "randomInt(${e(x.from)}, ${e(x.to)})"
        is Round -> "Math.round(${e(x.a)}).toDouble()"
        is ParseNumber -> "parseNumber(${e(x.a)})"
        is ListGet -> "${x.list}[${e(x.index)}.toInt() - 1]"
        is ListSize -> "${x.list}.size.toDouble()"
        is ViewText -> "${x.view}.text.toString()"
        is ViewChecked -> "${x.view}.isChecked"
        is RawExpr -> "(${x.code}).toString()"
        is StorageGet -> "(${x.store}.getString(${c(x.key)}, \"\") ?: \"\")"
        is TemplateExpr -> fill(x.code.kotlin, x.inputs, x.fields, ::e, ::str)
    }

    private fun Out.helpers(h: Set<Helper>) {
        if (Helper.FormatNumber in h) {
            line()
            line("private fun formatNumber(value: Double): String =")
            line("    if (value == Math.rint(value) && !value.isInfinite() && Math.abs(value) < 1e15) value.toLong().toString() else value.toString()")
        }
        if (Helper.RandomInt in h) {
            line()
            block("private fun randomInt(from: Double, to: Double): Double {") {
                line("val low = Math.ceil(minOf(from, to)).toInt()")
                line("val high = Math.floor(maxOf(from, to)).toInt()")
                line("if (high < low) return low.toDouble()")
                line("return (low + java.util.Random().nextInt(high - low + 1)).toDouble()")
            }
        }
        if (Helper.ParseNumber in h) {
            line()
            line("private fun parseNumber(text: String): Double = text.trim().toDoubleOrNull() ?: 0.0")
        }
    }

    internal fun str(s: String): String = JavaBackend.str(s).replace("$", "\\$")
}
